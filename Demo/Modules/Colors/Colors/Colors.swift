import UIKit

public extension UIColor {
    static let themeBackgroundPrimary: UIColor = .init(resource: .background)
    static let themeBackgroundSecondary: UIColor = .init(resource: .backgroundSecondary)
    static let themeForegroundPrimary: UIColor = .init(resource: .foreground)
    static let themeForegroundSecondary: UIColor = .init(resource: .foregroundSecondary)
}
